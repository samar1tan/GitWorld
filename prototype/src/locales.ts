export type MessageKey = keyof typeof messages.en;
export type MessageParameters = {
  yearValue: { year: number };
  periodValue: { from: number; to: number };
  processCount: { count: number };
  recordCount: { visible: number; total: number };
  sourceCount: { count: number };
  regionCount: { count: number };
  coverageCount: { count: number };
};
export function formatMessage<K extends keyof MessageParameters>(
  locale: keyof typeof messages,
  key: K,
  parameters: MessageParameters[K],
) {
  const number = new Intl.NumberFormat(locale, { useGrouping: false });
  return Object.entries(parameters).reduce<string>(
    (result, [name, value]) =>
      result.replaceAll(
        `{${name}}`,
        typeof value === "number" ? number.format(value) : String(value),
      ),
    messages[locale][key],
  );
}
