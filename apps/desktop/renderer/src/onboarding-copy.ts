export type OnboardingCopyKey = keyof typeof messages.en;
type Params = { progress: { completed: number; total: number }; progressSummary: { completed: number; total: number } };
export function onboardingCopy<K extends OnboardingCopyKey>(locale: HistoryLocale, key: K, ...args: K extends keyof Params ? [Params[K]] : []): string {
  let message: string = messages[locale][key];
  for (const [name, value] of Object.entries(args[0] ?? {})) message = message.replaceAll(`{${name}}`, new Intl.NumberFormat(locale).format(value));
  return message;
}
